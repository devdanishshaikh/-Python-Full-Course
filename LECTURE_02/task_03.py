# String Function 
# 1. .endswith()
name = "danish"
# "if yes print true f not then false"
print(name.endswith("ish"))   

# 2. .replace()
print(name.replace("danish", "ali"))  # replace the name with ali

# 3/ .capitalize()
print(name.capitalize()) # capitalize the first letter of the name

# 4.find()  
print(name.find("i")) #

# 5. .count()
print(name.count("i"))